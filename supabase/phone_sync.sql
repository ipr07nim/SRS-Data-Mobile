-- Phone sync: shared clock, one row per station tap, SRS links on rolls.
-- Additive and safe to re-run. Do NOT re-run schema.sql, which drops every table.

-- Shared clock. Phones measure their offset from this so every phone shows the same elapsed time.
create or replace function public.server_now_ms()
returns bigint
language sql
volatile
as $$
  select (extract(epoch from clock_timestamp()) * 1000)::bigint
$$;

grant execute on function public.server_now_ms() to anon, authenticated;

-- Where the roll started (Hill 1 line or Hill 2) and which SRS plan entry it was.
-- Pusher names stay in rolls.config_snapshot, copied when the roll opens.
alter table public.rolls
  add column if not exists origin_station text,
  add column if not exists srs_roll_date date,
  add column if not exists srs_roll_number integer,
  add column if not exists srs_buggy_id integer;

do $$
begin
  if not exists (
    select 1 from pg_constraint where conname = 'rolls_origin_station_check'
  ) then
    alter table public.rolls
      add constraint rolls_origin_station_check
      check (origin_station is null or origin_station in ('start', 'h1h2'));
  end if;
end $$;

-- One row per tap. Undo sets undone_at instead of deleting, so every phone sees it.
create table if not exists public.roll_taps (
  id bigint generated by default as identity primary key,
  roll_id bigint not null references public.rolls (id) on delete cascade,
  station_id text not null
    check (station_id in ('start', 'h1h2', 'h2h3', 'h3h4', 'h4h5', 'finish')),
  server_ms bigint not null,
  client_id text,
  created_at timestamp with time zone not null default now(),
  undone_at timestamp with time zone
);

create index if not exists roll_taps_roll_id_idx on public.roll_taps (roll_id);

-- At most one live tap per station per roll; a second phone at the same station loses the race.
create unique index if not exists roll_taps_one_live_idx
  on public.roll_taps (roll_id, station_id)
  where undone_at is null;

alter table public.roll_taps enable row level security;

drop policy if exists "roll_taps anon read" on public.roll_taps;
create policy "roll_taps anon read" on public.roll_taps
  for select to anon, authenticated using (true);

drop policy if exists "roll_taps anon insert" on public.roll_taps;
create policy "roll_taps anon insert" on public.roll_taps
  for insert to anon, authenticated with check (true);

drop policy if exists "roll_taps anon undo" on public.roll_taps;
create policy "roll_taps anon undo" on public.roll_taps
  for update to anon, authenticated using (true) with check (true);

grant select, insert, update on public.roll_taps to anon, authenticated;
grant usage, select on sequence public.roll_taps_id_seq to anon, authenticated;

-- Realtime: phones follow new rolls, status changes, and taps.
do $$
begin
  if not exists (select 1 from pg_publication where pubname = 'supabase_realtime') then
    create publication supabase_realtime;
  end if;
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'rolls'
  ) then
    alter publication supabase_realtime add table public.rolls;
  end if;
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'roll_taps'
  ) then
    alter publication supabase_realtime add table public.roll_taps;
  end if;
end $$;

-- Leaderboard: a roll that started at Hill 2 has no Hill 1 time, so its total is not comparable
-- and is left out of the overall ("all") board. Per-hill boards still use its splits.
create or replace function public.refresh_leaderboard_cache()
returns void
language plpgsql
as $$
declare
  hill_val text;
  buggy_val text;
  buggy_opts text[] := array['all', 'Inviscid', 'Kingpin', 'Seraph', 'Zuke'];
  hill_opts text[] := array['all', 'H1', 'H2', 'H3', 'H4', 'H5'];
begin
  foreach hill_val in array hill_opts loop
    foreach buggy_val in array buggy_opts loop
      insert into public.leaderboard_cache (hill, buggy_filter, entries, computed_at)
      values (
        hill_val,
        buggy_val,
        (
          with completed as (
            select r.*
            from public.rolls r
            where r.status = 'completed'
              and r.total_ms is not null
              and r.total_ms > 0
              and (buggy_val = 'all' or r.buggy = buggy_val)
              and (hill_val <> 'all' or coalesce(r.origin_station, 'start') = 'start')
          ),
          ranked as (
            select
              c.id as roll_id,
              c.driver,
              c.buggy,
              c.start_time_ms,
              case
                when hill_val = 'all' then c.total_ms
                else s.split_ms
              end as time_ms,
              case
                when hill_val = 'all' then
                  to_char((c.total_ms / 60000), 'FM0') || ':' ||
                  lpad(to_char((c.total_ms / 1000) % 60, 'FM00'), 2, '0') || '.' ||
                  lpad(to_char((c.total_ms % 1000) / 10, 'FM00'), 2, '0')
                else s.time_display
              end as time_str,
              case when hill_val = 'all' then '' else coalesce(s.pusher, '') end as pusher
            from completed c
            left join public.roll_splits s
              on s.roll_id = c.id
              and hill_val <> 'all'
              and s.hill = substring(hill_val from 2)::smallint
            where hill_val = 'all' or s.id is not null
          )
          select coalesce(jsonb_agg(row_to_json(t) order by t."timeMs" asc), '[]'::jsonb)
          from (
            select
              row_number() over (order by time_ms asc) as rank,
              roll_id::text as "rollId",
              pusher as name,
              driver,
              buggy,
              time_str as time,
              time_ms as "timeMs",
              to_char(to_timestamp(start_time_ms / 1000.0) at time zone 'America/New_York', 'MM/DD/YY') as date,
              to_char(to_timestamp(start_time_ms / 1000.0) at time zone 'America/New_York', 'HH12:MI AM') as "timeDisplay"
            from ranked
            where time_ms is not null and time_ms > 0
            order by time_ms asc
            limit 5
          ) t
        ),
        now()
      )
      on conflict (hill, buggy_filter)
      do update set entries = excluded.entries, computed_at = excluded.computed_at;
    end loop;
  end loop;
end;
$$;
