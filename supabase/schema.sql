-- Daily pusher assignments (one per hill per day)
create table public.assignments (
  id bigint generated by default as identity primary key,
  roll_date date not null default current_date,
  hill text not null check (hill in ('H1','H2','H3','H4','H5')),
  pusher_name text not null default '',
  assigned_by text not null default '',
  updated_at timestamp with time zone not null default now(),
  constraint assignments_date_hill_unique unique (roll_date, hill)
);

create index assignments_date_idx on public.assignments (roll_date);

-- Roll order queue for a rolls-day
create table public.roll_order (
  id bigint generated by default as identity primary key,
  roll_date date not null default current_date,
  position smallint not null,
  buggy text not null,
  driver text not null default '',
  status text not null default 'queued'
    check (status in ('queued', 'active', 'done', 'scratched')),
  created_at timestamp with time zone not null default now(),
  constraint roll_order_date_position_unique unique (roll_date, position)
);

create index roll_order_date_idx on public.roll_order (roll_date);

