-- Completed / active / cancelled rolls (live sync during timing)
create table public.rolls (
  id bigint generated by default as identity not null,
  start_time_ms bigint not null,
  driver text,
  buggy text,
  total_ms bigint,
  weather jsonb,
  notes text default '' not null,
  unreliable_stations text[] default '{}' not null,
  exported_at bigint,
  status text not null default 'active'
    check (status in ('active', 'completed', 'cancelled')),
  records jsonb not null default '{}',
  config_snapshot jsonb not null default '{}',
  client_id text,
  flagger_notes jsonb not null default '[]',
  video_url text,
  created_at timestamp with time zone not null default now(),
  constraint rolls_pkey primary key (id)
);

create index rolls_status_idx on public.rolls (status);
create index rolls_client_active_idx on public.rolls (client_id, status) where status = 'active';
create index rolls_start_time_ms_idx on public.rolls (start_time_ms desc);

-- One row per hill split (written on export / finalize)
create table public.roll_splits (
  id bigint generated by default as identity not null,
  roll_id bigint not null references public.rolls (id) on delete cascade,
  hill smallint not null check (hill between 1 and 5),
  time_display text not null,
  split_ms bigint not null,
  pusher text,
  created_at timestamp with time zone not null default now(),
  constraint roll_splits_pkey primary key (id),
  constraint roll_splits_roll_hill_unique unique (roll_id, hill)
);

create index roll_splits_roll_id_idx on public.roll_splits (roll_id);

-- Per-device settings (client_id from localStorage, persistent across tabs/reloads)
create table public.user_settings (
  id bigint generated by default as identity not null,
  client_id text not null,
  display_name text,
  theme text default 'system',
  direct_to_logs boolean default true,
  role_view text default 'pusher',
  last_viewed_roll_id bigint references public.rolls (id) on delete set null,
  created_at timestamp with time zone not null default now(),
  updated_at timestamp with time zone not null default now(),
  constraint user_settings_pkey primary key (id),
  constraint user_settings_client_id_unique unique (client_id)
);

-- Daily leaderboard snapshot (refreshed at midnight)
create table public.leaderboard_cache (
  id bigint generated by default as identity not null,
  hill text not null,
  buggy_filter text not null default 'all',
  entries jsonb not null default '[]',
  computed_at timestamp with time zone not null default now(),
  constraint leaderboard_cache_pkey primary key (id),
  constraint leaderboard_cache_hill_buggy_unique unique (hill, buggy_filter)
);

-- Recompute all hill × buggy leaderboard slices from completed rolls (positive times only)
create or replace function public.refresh_leaderboard_cache()
returns void
language plpgsql
as $$
declare
  hill_val text;
  buggy_val text;
  buggy_opts text[] := array['all', 'Inviscid', 'Kingpin', 'Seraph', 'Zuke'];
  hill_opts text[] := array['all', 'H1', 'H2', 'H3', 'H4', 'H5'];
begin
  foreach hill_val in array hill_opts loop
    foreach buggy_val in array buggy_opts loop
      insert into public.leaderboard_cache (hill, buggy_filter, entries, computed_at)
      values (
        hill_val,
        buggy_val,
        (
          with completed as (
            select r.*
            from public.rolls r
            where r.status = 'completed'
              and r.total_ms is not null
              and r.total_ms > 0
              and (buggy_val = 'all' or r.buggy = buggy_val)
          ),
          ranked as (
            select
              c.id as roll_id,
              c.driver,
              c.buggy,
              c.start_time_ms,
              case
                when hill_val = 'all' then c.total_ms
                else s.split_ms
              end as time_ms,
              case
                when hill_val = 'all' then
                  to_char((c.total_ms / 60000), 'FM0') || ':' ||
                  lpad(to_char((c.total_ms / 1000) % 60, 'FM00'), 2, '0') || '.' ||
                  lpad(to_char((c.total_ms % 1000) / 10, 'FM00'), 2, '0')
                else s.time_display
              end as time_str,
              case when hill_val = 'all' then '' else coalesce(s.pusher, '') end as pusher
            from completed c
            left join public.roll_splits s
              on s.roll_id = c.id
              and hill_val <> 'all'
              and s.hill = substring(hill_val from 2)::smallint
            where hill_val = 'all' or s.id is not null
          )
          select coalesce(jsonb_agg(row_to_json(t) order by t."timeMs" asc), '[]'::jsonb)
          from (
            select
              row_number() over (order by time_ms asc) as rank,
              roll_id::text as "rollId",
              pusher as name,
              driver,
              buggy,
              time_str as time,
              time_ms as "timeMs",
              to_char(to_timestamp(start_time_ms / 1000.0) at time zone 'America/New_York', 'MM/DD/YY') as date,
              to_char(to_timestamp(start_time_ms / 1000.0) at time zone 'America/New_York', 'HH12:MI AM') as "timeDisplay"
            from ranked
            where time_ms is not null and time_ms > 0
            order by time_ms asc
            limit 5
          ) t
        ),
        now()
      )
      on conflict (hill, buggy_filter)
      do update set entries = excluded.entries, computed_at = excluded.computed_at;
    end loop;
  end loop;
end;
$$;

