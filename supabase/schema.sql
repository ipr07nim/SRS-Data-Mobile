create or replace view public.roll_stats_view as
select
  r.id as roll_id,
  r.driver,
  r.buggy,
  r.total_ms,
  r.start_time_ms,
  to_char(to_timestamp(r.start_time_ms / 1000.0) at time zone 'America/New_York', 'YYYY-MM-DD') as roll_date,
  r.weather,
  r.notes,
  r.flagger_notes,
  r.unreliable_stations,
  r.status,
  s.hill,
  s.split_ms,
  s.time_display as split_display,
  s.pusher
from public.rolls r
left join public.roll_splits s on s.roll_id = r.id
where r.status = 'completed' and r.total_ms is not null and r.total_ms > 0;

create or replace view public.driver_stats_view as
select
  r.driver,
  count(*) as roll_count,
  round(avg(r.total_ms)) as avg_total_ms,
  min(r.total_ms) as best_total_ms
from public.rolls r
where r.status = 'completed' and r.total_ms is not null and r.total_ms > 0
  and r.driver is not null and r.driver <> ''
group by r.driver;

create or replace view public.buggy_stats_view as
select
  r.buggy,
  count(*) as roll_count,
  round(avg(r.total_ms)) as avg_total_ms,
  min(r.total_ms) as best_total_ms
from public.rolls r
where r.status = 'completed' and r.total_ms is not null and r.total_ms > 0
  and r.buggy is not null and r.buggy <> ''
group by r.buggy;
